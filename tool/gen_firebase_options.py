"""Generates lib/online/firebase_options.dart from the Firebase config files.

Usage (from the repo root):
    python3 tool/gen_firebase_options.py

Reads:
    firebase/google-services.json      (Android app config from Firebase)
    firebase/GoogleService-Info.plist  (iOS app config from Firebase)

These files are not secret: Firebase security comes from firestore.rules.
"""
import json
import plistlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ANDROID_PACKAGE = "com.github.skydodger.sky_dodger"
IOS_BUNDLE = "com.github.skydodger.skyDodger"


def dart_str(v):
    return "null" if v is None else "'" + str(v).replace("'", "\\'") + "'"


def main():
    gs = json.loads((ROOT / "firebase/google-services.json").read_text())
    plist = plistlib.loads((ROOT / "firebase/GoogleService-Info.plist").read_bytes())

    proj = gs["project_info"]
    client = next(
        c for c in gs["client"]
        if c["client_info"]["android_client_info"]["package_name"] == ANDROID_PACKAGE
    )
    oauth = client.get("oauth_client", [])
    web_ids = [o["client_id"] for o in oauth if o.get("client_type") == 3]
    for svc in client.get("services", {}).get("appinvite_service", {}).get("other_platform_oauth_client", []):
        if svc.get("client_type") == 3:
            web_ids.append(svc["client_id"])
    web_client_id = web_ids[0] if web_ids else None

    if plist.get("BUNDLE_ID") != IOS_BUNDLE:
        print(f"WARNING: iOS bundle id is {plist.get('BUNDLE_ID')}, expected {IOS_BUNDLE}")
    if not web_client_id:
        print("WARNING: no web (server) OAuth client id found - enable Google sign-in "
              "in Firebase Authentication, then download google-services.json again.")
    if "CLIENT_ID" not in plist:
        print("WARNING: GoogleService-Info.plist has no CLIENT_ID - enable Google "
              "sign-in first, then download the plist again.")

    out = f"""// GENERATED by tool/gen_firebase_options.py - do not edit by hand.
// ignore_for_file: lines_longer_than_80_chars
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

class DefaultFirebaseOptions {{
  /// Options for the current platform, or null where Firebase isn't set up.
  static FirebaseOptions? get currentPlatform {{
    if (kIsWeb) return null;
    switch (defaultTargetPlatform) {{
      case TargetPlatform.android:
        return android;
      case TargetPlatform.iOS:
        return ios;
      default:
        return null;
    }}
  }}

  static const FirebaseOptions android = FirebaseOptions(
    apiKey: {dart_str(client['api_key'][0]['current_key'])},
    appId: {dart_str(client['client_info']['mobilesdk_app_id'])},
    messagingSenderId: {dart_str(proj['project_number'])},
    projectId: {dart_str(proj['project_id'])},
    storageBucket: {dart_str(proj.get('storage_bucket'))},
  );

  static const FirebaseOptions ios = FirebaseOptions(
    apiKey: {dart_str(plist['API_KEY'])},
    appId: {dart_str(plist['GOOGLE_APP_ID'])},
    messagingSenderId: {dart_str(plist['GCM_SENDER_ID'])},
    projectId: {dart_str(plist['PROJECT_ID'])},
    storageBucket: {dart_str(plist.get('STORAGE_BUCKET'))},
    iosClientId: {dart_str(plist.get('CLIENT_ID'))},
    iosBundleId: {dart_str(plist.get('BUNDLE_ID'))},
  );
}}

/// OAuth client ids used by Google Sign-In.
class GoogleSignInIds {{
  /// "Web client" id: Android needs it to get an ID token for Firebase.
  static const String? serverClientId = {dart_str(web_client_id)};

  /// iOS client id (also registered as a URL scheme in Info.plist by CI).
  static const String? iosClientId = {dart_str(plist.get('CLIENT_ID'))};
}}
"""
    (ROOT / "lib/online/firebase_options.dart").write_text(out)
    print("Wrote lib/online/firebase_options.dart")


if __name__ == "__main__":
    sys.exit(main())
